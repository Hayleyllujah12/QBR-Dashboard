/* Builds qbr-app/libs/tesseract/offline/*.js — the vendored Tesseract.js worker, the two LSTM
 * core variants and the English model wrapped as plain <script> files, so OCR runs from file://
 * (browsers block Web Worker scripts, importScripts and fetch of file:// URLs; a classic <script>
 * tag still loads). js/scan.js injects these on demand and starts the worker from a blob URL.
 *
 * Also applies ONE targeted fix to the worker source (Tesseract.js 5.1.1 bug): when language data
 * is passed in memory as {code, data}, the worker's initialize step joins `t.data` (the raw bytes)
 * instead of `t.code` into the language string and hangs. The original worker.min.js is untouched.
 *
 * Re-run after updating anything in libs/tesseract/:   node tests/build-tesseract-offline.cjs
 */
const fs = require("fs"), path = require("path");
const app = [path.join(__dirname, "../qbr-app"), path.join(__dirname, "..")].find(d => fs.existsSync(path.join(d, "libs/tesseract/worker.min.js")));
if (!app) { console.error("libs/tesseract/worker.min.js not found next to this script"); process.exit(2); }
const T = path.join(app, "libs/tesseract"), O = path.join(T, "offline");
fs.mkdirSync(O, { recursive: true });
const wrap = (file, key, val) => {
  const out = "/* generated by tests/build-tesseract-offline.cjs - do not edit; offline Tesseract asset (" + key + ") */\n" +
    "(window.__QBR_TESS = window.__QBR_TESS || {})[" + JSON.stringify(key) + "] = " + JSON.stringify(val) + ";\n";
  fs.writeFileSync(path.join(O, file), out);
  console.log("  " + file.padEnd(20) + (out.length / 1048576).toFixed(2) + " MB");
};
let worker = fs.readFileSync(path.join(T, "worker.min.js"), "utf8");
const bad = 'return"string"==typeof t?t:t.data})).join("+")', good = 'return"string"==typeof t?t:t.code})).join("+")';
const n = worker.split(bad).length - 1;
if (n !== 1) { console.error("worker.min.js: expected the lang-join pattern exactly once, found " + n + " (Tesseract.js version changed?)"); process.exit(1); }
worker = worker.replace(bad, good);
wrap("worker.js", "worker", worker);
wrap("core-simd-lstm.js", "core-simd-lstm", fs.readFileSync(path.join(T, "tesseract-core-simd-lstm.wasm.js"), "utf8"));
wrap("core-lstm.js", "core-lstm", fs.readFileSync(path.join(T, "tesseract-core-lstm.wasm.js"), "utf8"));
wrap("eng.js", "eng", fs.readFileSync(path.join(T, "eng.traineddata.gz")).toString("base64"));
console.log("done -> " + O);
