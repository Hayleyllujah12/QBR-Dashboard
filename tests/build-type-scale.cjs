// Generates css/type-scale.css from css/styles.css (v1.31.0 Admin › Appearance text sizes).
// Every rule that sets font-size / line-height in px gets a twin, prefixed with
// :root[data-qbr-fs], whose sizes are multiplied by --fs-t (body text) or --fs-h (headings,
// titles and big numbers >= 18px). The twins only apply while the Admin panel has a custom
// size set (admin.js adds data-qbr-fs), so default rendering is byte-for-byte unchanged and
// styles.css itself is never edited.
// Usage: node tests/build-type-scale.cjs            (writes css/type-scale.css)
//        node tests/build-type-scale.cjs --check    (exit 1 if the file is stale)
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const APP = fs.existsSync(path.join(ROOT, "qbr-app/index.html")) ? path.join(ROOT, "qbr-app") : ROOT;
const SRC = path.join(APP, "css/styles.css"), OUT = path.join(APP, "css/type-scale.css");
const HEAD = /(^|[\s>+~(,])h[1-6]\b|\.h[1-6]\b|\.dash-h|title|\.sb-gh|kpi-v|-value|hero|thi-score|\.app-title/i;

function splitTop(s, sep) {            // split on sep outside (), []
  const out = []; let d = 0, cur = "";
  for (const ch of s) { if (ch === "(" || ch === "[") d++; if (ch === ")" || ch === "]") d--; if (ch === sep && !d) { out.push(cur); cur = ""; } else cur += ch; }
  if (cur.trim()) out.push(cur); return out;
}
function prefix(sel) {
  return splitTop(sel, ",").map(s => s.trim()).filter(Boolean).map(s => {
    if (/^:root\b/.test(s)) return s.replace(/^:root/, ":root[data-qbr-fs]");
    if (/^html\b/.test(s)) return s.replace(/^html/, "html[data-qbr-fs]");
    return ":root[data-qbr-fs] " + s;
  }).join(",");
}
function rules(css) {                  // returns [{media, sel, body}] (one level of @media)
  const out = []; let i = 0;
  const block = (from) => { let d = 0; for (let j = from; j < css.length; j++) { if (css[j] === "{") d++; else if (css[j] === "}") { d--; if (!d) return j; } } return css.length; };
  while (i < css.length) {
    const o = css.indexOf("{", i); if (o < 0) break;
    const head = css.slice(i, o).trim(), end = block(o);
    if (head.startsWith("@media")) {
      const inner = css.slice(o + 1, end);
      rules(inner).forEach(r => out.push({ media: head, sel: r.sel, body: r.body }));
    } else if (!head.startsWith("@")) out.push({ media: "", sel: head, body: css.slice(o + 1, end) });
    i = end + 1;
  }
  return out;
}
function build() {
  const css = fs.readFileSync(SRC, "utf8").replace(/\r/g, "").replace(/\/\*[\s\S]*?\*\//g, "");
  const lines = ["/* GENERATED by tests/build-type-scale.cjs from styles.css — do not edit by hand. */",
    "/* Active only while Admin › Appearance has a custom text size (admin.js sets :root[data-qbr-fs]). */"];
  // Bootstrap defaults first (rem-based, lowest priority); app rules below override them.
  [["h1", 2.5], ["h2", 2], ["h3", 1.75], ["h4", 1.5], ["h5", 1.25], ["h6", 1]].forEach(([h, rem]) =>
    lines.push(`:root[data-qbr-fs] ${h},:root[data-qbr-fs] .${h}{font-size:calc(${rem}rem * var(--fs-h,1))}`));
  // Bootstrap controls are rem-based (don't follow body): scale them with body text.
  lines.push(":root[data-qbr-fs] .btn,:root[data-qbr-fs] .form-control,:root[data-qbr-fs] .form-select{font-size:calc(1rem * var(--fs-t,1))}");
  lines.push(":root[data-qbr-fs] .btn-sm,:root[data-qbr-fs] .form-control-sm,:root[data-qbr-fs] .form-select-sm{font-size:calc(.875rem * var(--fs-t,1))}");
  let n = 0;
  for (const r of rules(css)) {
    if (/print/.test(r.media)) continue;
    const decls = [];
    for (const m of r.body.matchAll(/(font-size|line-height)\s*:\s*([\d.]+)px\s*(!important)?/g)) {
      const px = parseFloat(m[2]); if (!px) continue;
      const head = HEAD.test(r.sel) || (m[1] === "font-size" && px >= 18);
      decls.push(`${m[1]}:calc(${m[2]}px * var(${head ? "--fs-h" : "--fs-t"},1))${m[3] ? " !important" : ""}`);
    }
    if (!decls.length) continue;
    const rule = `${prefix(r.sel)}{${decls.join(";")}}`;
    lines.push(r.media ? `${r.media}{${rule}}` : rule); n++;
  }
  return { text: lines.join("\n") + "\n", n };
}
const { text, n } = build();
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r/g, "") : "";
  if (cur !== text) { console.log("type-scale.css is STALE — run: node tests/build-type-scale.cjs"); process.exit(1); }
  console.log("type-scale.css up to date (" + n + " rules)"); process.exit(0);
}
fs.writeFileSync(OUT, text.replace(/\n/g, "\r\n"));
console.log("wrote " + OUT + " (" + n + " scaled rules)");
